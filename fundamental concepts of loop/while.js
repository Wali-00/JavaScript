let num =0;
while(num<5){
    console.log(num);
    num++;
}// while loop is used to execute a block of code repeatedly as long as a specified condition is true. In this example, we initialize num to 0 and use a while loop to log the value of num to the console and then increment it by 1. The loop continues until num is no longer less than 5. The output will be:
// 0
// 1
// 2
// 3
// 4