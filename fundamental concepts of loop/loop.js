const num = [1, 2, 3, 4, 5];
// for loop

for(number of num){
    console.log(number);
}
// for...of loop is used to iterate over the elements of an iterable object (like an array). It allows you to access each element directly without needing to use an index. In this example, we loop through the num array and log each number to the console. The output will be:
// 1
// 2
// 3
// 4
// 5
